//! Generated TypeScript for this crate's shapes, in `ui/src/api/generated/panel/`.
//! Regenerate after changing a type:
//!
//! ```text
//! HELM_UPDATE_BINDINGS=1 cargo test -p helm-panel bindings_are_current
//! ```

use crate::archive::{ArchiveEntry, ArchiveView};
use crate::changes::{ChangeRecord, ChangesView, DiffView, Section};
use crate::handler::{Handler, Refusal};
use crate::quick::{QuickItem, QuickResult};
use crate::turns::{TurnChanges, TurnDiff, TurnFile};
use crate::viewer::{DirEntry, FileStamp, FileView, ViewKind};
use std::path::{Path, PathBuf};
use ts_rs::TS;

pub fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../ui/src/api/generated/panel")
}

/// Write every binding into `dir`. Returns the file names written, sorted, `index.ts` last.
pub fn export(dir: &Path) -> Result<Vec<String>, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    FileView::export_all_to(dir).map_err(|e| e.to_string())?;
    FileStamp::export_all_to(dir).map_err(|e| e.to_string())?;
    ArchiveView::export_all_to(dir).map_err(|e| e.to_string())?;
    Handler::export_all_to(dir).map_err(|e| e.to_string())?;
    Refusal::export_all_to(dir).map_err(|e| e.to_string())?;
    QuickResult::export_all_to(dir).map_err(|e| e.to_string())?;
    ChangesView::export_all_to(dir).map_err(|e| e.to_string())?;
    DiffView::export_all_to(dir).map_err(|e| e.to_string())?;
    TurnChanges::export_all_to(dir).map_err(|e| e.to_string())?;
    TurnDiff::export_all_to(dir).map_err(|e| e.to_string())?;
    let mut names = vec![
        ViewKind::ident(),
        DirEntry::ident(),
        FileView::ident(),
        FileStamp::ident(),
        ArchiveEntry::ident(),
        ArchiveView::ident(),
        Handler::ident(),
        Refusal::ident(),
        QuickItem::ident(),
        QuickResult::ident(),
        Section::ident(),
        ChangeRecord::ident(),
        ChangesView::ident(),
        DiffView::ident(),
        TurnFile::ident(),
        TurnChanges::ident(),
        TurnDiff::ident(),
    ];
    names.sort();
    let mut index = String::from(
        "// Generated by host/crates/panel (bindings.rs). Do not edit: change the Rust types and\n\
         // regenerate with `HELM_UPDATE_BINDINGS=1 cargo test -p helm-panel bindings_are_current`.\n",
    );
    for n in &names {
        index.push_str(&format!("export type {{ {n} }} from './{n}.ts';\n"));
    }
    std::fs::write(dir.join("index.ts"), index).map_err(|e| e.to_string())?;
    let mut files: Vec<String> = names.iter().map(|n| format!("{n}.ts")).collect();
    files.push("index.ts".into());
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn read_all(dir: &Path) -> Vec<(String, String)> {
        let mut out: Vec<(String, String)> = std::fs::read_dir(dir)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .filter(|e| e.path().is_file())
                    .map(|e| {
                        let text = std::fs::read_to_string(e.path())
                            .unwrap_or_default()
                            .replace("\r\n", "\n");
                        (e.file_name().to_string_lossy().into_owned(), text)
                    })
                    .collect()
            })
            .unwrap_or_default();
        out.sort();
        out
    }

    #[test]
    fn bindings_are_current() {
        let committed = committed_dir();
        if std::env::var_os("HELM_UPDATE_BINDINGS").is_some() {
            if committed.exists() {
                for e in std::fs::read_dir(&committed).unwrap().flatten() {
                    if e.path().is_file() {
                        std::fs::remove_file(e.path()).unwrap();
                    }
                }
            }
            export(&committed).unwrap();
        }
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        assert_eq!(
            read_all(&committed),
            read_all(tmp.path()),
            "ui/src/api/generated/panel is out of date: regenerate it (see bindings.rs)"
        );
    }

    #[test]
    fn numbers_are_never_bigint() {
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        for (name, text) in read_all(tmp.path()) {
            assert!(!text.contains("bigint"), "{name} uses bigint");
        }
    }
}
