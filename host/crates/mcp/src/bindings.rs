//! Generated TypeScript for this crate's shapes, in `ui/src/api/generated/mcp/`. Regenerate after
//! changing a type:
//!
//! ```text
//! HELM_UPDATE_BINDINGS=1 cargo test -p helm-mcp bindings_are_current
//! ```

use crate::types::*;
use std::path::{Path, PathBuf};
use ts_rs::TS;

pub fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../ui/src/api/generated/mcp")
}

/// Write every binding into `dir`. Returns the file names written, sorted, `index.ts` last.
pub fn export(dir: &Path) -> Result<Vec<String>, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    McpEditorSnapshot::export_all_to(dir).map_err(|e| e.to_string())?;
    AgentSnapshot::export_all_to(dir).map_err(|e| e.to_string())?;
    McpServerSaveArgs::export_all_to(dir).map_err(|e| e.to_string())?;
    McpServerRemoveArgs::export_all_to(dir).map_err(|e| e.to_string())?;
    McpServerEnableArgs::export_all_to(dir).map_err(|e| e.to_string())?;
    crate::presets::McpPreset::export_all_to(dir).map_err(|e| e.to_string())?;
    crate::status::ServerStatus::export_all_to(dir).map_err(|e| e.to_string())?;
    crate::repo_gate::RepoServer::export_all_to(dir).map_err(|e| e.to_string())?;
    crate::repo_gate::LaunchGate::export_all_to(dir).map_err(|e| e.to_string())?;
    let mut names = vec![
        McpEditorSnapshot::ident(),
        McpServer::ident(),
        Transport::ident(),
        TransportKind::ident(),
        ValueRef::ident(),
        RefKind::ident(),
        OAuthConfig::ident(),
        AgentSnapshot::ident(),
        AgentServerView::ident(),
        McpServerSaveArgs::ident(),
        McpServerRemoveArgs::ident(),
        McpServerEnableArgs::ident(),
        crate::presets::McpPreset::ident(),
        crate::status::ServerStatus::ident(),
        crate::status::ServerState::ident(),
        crate::repo_gate::RepoServer::ident(),
        crate::repo_gate::RepoServerState::ident(),
        crate::repo_gate::LaunchGate::ident(),
    ];
    names.sort();
    let mut index = String::from(
        "// Generated by host/crates/mcp (bindings.rs). Do not edit: change the Rust types and\n\
         // regenerate with `HELM_UPDATE_BINDINGS=1 cargo test -p helm-mcp bindings_are_current`.\n",
    );
    for n in &names {
        index.push_str(&format!("export type {{ {n} }} from './{n}.ts';\n"));
    }
    std::fs::write(dir.join("index.ts"), index).map_err(|e| e.to_string())?;
    let mut files: Vec<String> = names.iter().map(|n| format!("{n}.ts")).collect();
    files.push("index.ts".into());
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn read_all(dir: &Path) -> Vec<(String, String)> {
        let mut out: Vec<(String, String)> = std::fs::read_dir(dir)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .filter(|e| e.path().is_file())
                    .map(|e| {
                        let text = std::fs::read_to_string(e.path())
                            .unwrap_or_default()
                            .replace("\r\n", "\n");
                        (e.file_name().to_string_lossy().into_owned(), text)
                    })
                    .collect()
            })
            .unwrap_or_default();
        out.sort();
        out
    }

    #[test]
    fn bindings_are_current() {
        let committed = committed_dir();
        if std::env::var_os("HELM_UPDATE_BINDINGS").is_some() {
            if committed.exists() {
                for e in std::fs::read_dir(&committed).unwrap().flatten() {
                    if e.path().is_file() {
                        std::fs::remove_file(e.path()).unwrap();
                    }
                }
            }
            export(&committed).unwrap();
        }
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        assert_eq!(
            read_all(&committed),
            read_all(tmp.path()),
            "ui/src/api/generated/mcp is out of date: regenerate it (see bindings.rs)"
        );
    }

    #[test]
    fn numbers_are_never_bigint() {
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        for (name, text) in read_all(tmp.path()) {
            assert!(!text.contains("bigint"), "{name} uses bigint");
        }
    }
}
