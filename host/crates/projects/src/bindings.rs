//! Generated TypeScript bindings for this crate.
//!
//! [`export`] writes one `.ts` file per type in [`crate::types`] plus an `index.ts` into
//! `ui/src/api/generated/projects/`. `bindings_are_current` regenerates them into a temporary
//! folder and fails if anything differs from the committed files. To regenerate:
//!
//! ```text
//! HELM_UPDATE_BINDINGS=1 cargo test -p helm-projects bindings_are_current
//! ```

use crate::types::*;
use std::path::{Path, PathBuf};
use ts_rs::TS;

pub fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../ui/src/api/generated/projects")
}

macro_rules! roots {
    ($dir:expr, $($t:ty),* $(,)?) => {{
        $( <$t>::export_all_to($dir).map_err(|e| e.to_string())?; )*
    }};
}

pub fn export(dir: &Path) -> Result<Vec<String>, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    roots!(
        dir,
        ProjectNode,
        SidebarRow,
        SidebarPage,
        BoardSyncState,
        BoardConnection,
        ProjectListArgs,
        ProjectCreateArgs,
        ProjectUpdateArgs,
        ProjectIdArgs,
        SidebarPageArgs,
        SidebarRowsArgs,
        ChatOrganizeArgs,
        BoardConnectionSaveArgs,
    );
    let mut files: Vec<String> = std::fs::read_dir(dir)
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok())
        .filter(|e| e.file_type().map(|t| t.is_file()).unwrap_or(false))
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".ts") && n != "index.ts")
        .collect();
    files.sort();
    let mut index = String::from(
        "// Generated by host/crates/projects (bindings.rs). Do not edit: change the Rust types and\n\
         // regenerate with `HELM_UPDATE_BINDINGS=1 cargo test -p helm-projects bindings_are_current`.\n",
    );
    for f in &files {
        let stem = f.trim_end_matches(".ts");
        index.push_str(&format!("export type {{ {stem} }} from './{stem}.ts';\n"));
    }
    std::fs::write(dir.join("index.ts"), index).map_err(|e| e.to_string())?;
    files.push("index.ts".into());
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn read_all(dir: &Path) -> Vec<(String, String)> {
        let mut out: Vec<(String, String)> = std::fs::read_dir(dir)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .filter(|e| e.file_type().map(|t| t.is_file()).unwrap_or(false))
                    .map(|e| {
                        let name = e.file_name().to_string_lossy().into_owned();
                        let text = std::fs::read_to_string(e.path())
                            .unwrap_or_default()
                            .replace("\r\n", "\n");
                        (name, text)
                    })
                    .collect()
            })
            .unwrap_or_default();
        out.sort();
        out
    }

    #[test]
    fn bindings_are_current() {
        let committed = committed_dir();
        if std::env::var_os("HELM_UPDATE_BINDINGS").is_some() {
            if committed.exists() {
                for e in std::fs::read_dir(&committed).unwrap().flatten() {
                    if e.file_type().map(|t| t.is_file()).unwrap_or(false) {
                        std::fs::remove_file(e.path()).unwrap();
                    }
                }
            }
            export(&committed).unwrap();
        }
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        let fresh = read_all(tmp.path());
        let current = read_all(&committed);
        let names = |v: &[(String, String)]| v.iter().map(|(n, _)| n.clone()).collect::<Vec<_>>();
        assert_eq!(
            names(&current),
            names(&fresh),
            "ui/src/api/generated/projects is out of date: regenerate it (see bindings.rs)"
        );
        for ((name, a), (_, b)) in current.iter().zip(fresh.iter()) {
            assert_eq!(a, b, "{name} is out of date: regenerate (see bindings.rs)");
        }
    }

    #[test]
    fn numbers_are_never_bigint() {
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        for (name, text) in read_all(tmp.path()) {
            assert!(!text.contains("bigint"), "{name} uses bigint");
        }
    }
}
