//! Generated TypeScript bindings.
//!
//! [`export`] writes one `.ts` file per type in [`crate::types`] plus an `index.ts` that re-exports
//! them all, into `ui/src/api/generated/`. The `bindings_are_current` test regenerates them into a
//! temporary folder and fails if anything differs from the committed files.
//!
//! The root of `generated/` is this crate's alone. Other crates write their own subfolders
//! (`generated/<crate>/`), so everything here looks at the root's files only and
//! never reads, compares or deletes a subfolder.
//!
//! To regenerate after changing a type:
//!
//! ```text
//! HELM_UPDATE_BINDINGS=1 cargo test -p helm-chats bindings_are_current
//! ```

use crate::types::*;
use std::path::{Path, PathBuf};
use ts_rs::TS;

/// Where the committed bindings live, relative to this crate.
pub fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../ui/src/api/generated")
}

macro_rules! roots {
    ($dir:expr, $($t:ty),* $(,)?) => {{
        let mut names: Vec<String> = Vec::new();
        $(
            <$t>::export_all_to($dir).map_err(|e| e.to_string())?;
            names.push(<$t>::ident());
        )*
        names
    }};
}

/// Write every binding into `dir` (created if missing). Returns the file names written.
pub fn export(dir: &Path) -> Result<Vec<String>, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    roots!(
        dir,
        ChatEvent,
        ChatGetResult,
        ChatSendResult,
        ChatStopResult,
        SubmissionActionResult,
        DraftSaveResult,
        ToolStopResult,
        TranscriptPage,
        ModelCatalogue,
        ChatCreateArgs,
        ChatIdArgs,
        TranscriptPageArgs,
        ChatSendArgs,
        ChatStopArgs,
        SubmissionActionArgs,
        InteractionAnswerArgs,
        DraftSaveArgs,
        ChatSetModelArgs,
        ModelCatalogueArgs,
        ToolStopArgs,
        AttentionSummary,
        Completion,
        UnreadClearArgs,
        CompletionAckArgs,
        ChatMuteArgs,
        AttentionSnoozeArgs,
        ChatForkArgs,
    );
    let mut files: Vec<String> = std::fs::read_dir(dir)
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok())
        .filter(|e| e.file_type().is_ok_and(|t| t.is_file()))
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".ts") && n != "index.ts")
        .collect();
    files.sort();
    let mut index = String::from(
        "// Generated by host/crates/chats (bindings.rs). Do not edit: change the Rust types and\n\
         // regenerate with `HELM_UPDATE_BINDINGS=1 cargo test -p helm-chats bindings_are_current`.\n",
    );
    for f in &files {
        let stem = f.trim_end_matches(".ts");
        index.push_str(&format!("export type {{ {stem} }} from './{stem}.ts';\n"));
    }
    std::fs::write(dir.join("index.ts"), index).map_err(|e| e.to_string())?;
    // ts-rs imports siblings without an extension; the UI's tsconfig resolves those (bundler
    // resolution), and every import is type-only, so node:test's type stripping erases them.
    files.push("index.ts".into());
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The root's files (subfolders belong to other crates and are skipped).
    fn read_all(dir: &Path) -> Vec<(String, String)> {
        let mut out: Vec<(String, String)> = std::fs::read_dir(dir)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .filter(|e| e.file_type().is_ok_and(|t| t.is_file()))
                    .map(|e| {
                        let name = e.file_name().to_string_lossy().into_owned();
                        let text = std::fs::read_to_string(e.path())
                            .unwrap_or_default()
                            .replace("\r\n", "\n");
                        (name, text)
                    })
                    .collect()
            })
            .unwrap_or_default();
        out.sort();
        out
    }

    #[test]
    fn bindings_are_current() {
        let committed = committed_dir();
        if std::env::var_os("HELM_UPDATE_BINDINGS").is_some() {
            if committed.exists() {
                for e in std::fs::read_dir(&committed).unwrap().flatten() {
                    if e.file_type().is_ok_and(|t| t.is_file()) {
                        std::fs::remove_file(e.path()).unwrap();
                    }
                }
            }
            export(&committed).unwrap();
        }
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        let fresh = read_all(tmp.path());
        let current = read_all(&committed);
        let names = |v: &[(String, String)]| v.iter().map(|(n, _)| n.clone()).collect::<Vec<_>>();
        assert_eq!(
            names(&current),
            names(&fresh),
            "ui/src/api/generated is out of date: regenerate it (see bindings.rs)"
        );
        for ((name, a), (_, b)) in current.iter().zip(fresh.iter()) {
            assert_eq!(
                a, b,
                "{name} is out of date: regenerate ui/src/api/generated (see bindings.rs)"
            );
        }
    }

    /// Another crate's `generated/<crate>/` folder is neither compared nor deleted.
    #[test]
    fn subfolders_are_left_alone() {
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        let before = read_all(tmp.path());
        let sub = tmp.path().join("projects");
        std::fs::create_dir_all(&sub).unwrap();
        std::fs::write(
            sub.join("ProjectNode.ts"),
            "export type ProjectNode = {};
",
        )
        .unwrap();
        assert_eq!(read_all(tmp.path()), before);
        let again = export(tmp.path()).unwrap();
        assert!(!again.iter().any(|n| n == "projects"));
        assert!(!std::fs::read_to_string(tmp.path().join("index.ts"))
            .unwrap()
            .contains("projects"));
        assert!(sub.join("ProjectNode.ts").is_file());
    }

    #[test]
    fn numbers_are_never_bigint() {
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        for (name, text) in read_all(tmp.path()) {
            assert!(!text.contains("bigint"), "{name} uses bigint");
        }
    }
}
