//! Generated TypeScript for this crate's shapes, in `ui/src/api/generated/gatekeeper/`.
//! Regenerate after changing a type:
//!
//! ```text
//! HELM_UPDATE_BINDINGS=1 cargo test -p helm-gatekeeper bindings_are_current
//! ```

use crate::store::GateAsk;
use crate::workmode::{BoardMode, Mode, ModeCounts, ModeSource, WorkModeView};
use std::path::{Path, PathBuf};
use ts_rs::TS;

pub fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../ui/src/api/generated/gatekeeper")
}

/// Write every binding into `dir`. Returns the file names written, sorted, `index.ts` last.
pub fn export(dir: &Path) -> Result<Vec<String>, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    GateAsk::export_all_to(dir).map_err(|e| e.to_string())?;
    WorkModeView::export_all_to(dir).map_err(|e| e.to_string())?;
    // The write-up types come from the chats crate and are already generated one folder up,
    // with the card's own shapes: point at that copy rather than keep a second one here.
    let ask = dir.join(format!("{}.ts", GateAsk::ident()));
    let text = std::fs::read_to_string(&ask).map_err(|e| e.to_string())?;
    let fixed = text.replace("\"./GateBrief\"", "\"../GateBrief\"");
    if fixed == text {
        return Err("GateAsk.ts does not import GateBrief as expected".into());
    }
    std::fs::write(&ask, fixed).map_err(|e| e.to_string())?;
    // The shapes that live in this folder (the working mode's), then the two re-exported ones.
    let own = [
        GateAsk::ident(),
        BoardMode::ident(),
        Mode::ident(),
        ModeCounts::ident(),
        ModeSource::ident(),
        WorkModeView::ident(),
    ];
    let mut names: Vec<String> = own.to_vec();
    for extra in [
        helm_chats::types::GateBrief::ident(),
        helm_chats::types::GateBriefOption::ident(),
    ] {
        let p = dir.join(format!("{extra}.ts"));
        if p.exists() {
            std::fs::remove_file(&p).map_err(|e| e.to_string())?;
        }
        names.push(extra);
    }
    names.sort();
    names.dedup();
    let mut index = String::from(
        "// Generated by host/crates/gatekeeper (bindings.rs). Do not edit: change the Rust types and\n\
         // regenerate with `HELM_UPDATE_BINDINGS=1 cargo test -p helm-gatekeeper bindings_are_current`.\n",
    );
    for n in &names {
        index.push_str(&format!(
            "export type {{ {n} }} from '{}{n}.ts';\n",
            if own.contains(n) { "./" } else { "../" }
        ));
    }
    std::fs::write(dir.join("index.ts"), index).map_err(|e| e.to_string())?;
    // Only this folder's own files are written; the two re-exported ones live one level up.
    let mut written: Vec<String> = own.iter().map(|n| format!("{n}.ts")).collect();
    written.push("index.ts".into());
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn read_all(dir: &Path) -> Vec<(String, String)> {
        let mut out: Vec<(String, String)> = std::fs::read_dir(dir)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .filter(|e| e.path().is_file())
                    .map(|e| {
                        let text = std::fs::read_to_string(e.path())
                            .unwrap_or_default()
                            .replace("\r\n", "\n");
                        (e.file_name().to_string_lossy().into_owned(), text)
                    })
                    .collect()
            })
            .unwrap_or_default();
        out.sort();
        out
    }

    #[test]
    fn bindings_are_current() {
        let committed = committed_dir();
        if std::env::var_os("HELM_UPDATE_BINDINGS").is_some() {
            if committed.exists() {
                for e in std::fs::read_dir(&committed).unwrap().flatten() {
                    if e.path().is_file() {
                        std::fs::remove_file(e.path()).unwrap();
                    }
                }
            }
            export(&committed).unwrap();
        }
        let tmp = tempfile::tempdir().unwrap();
        for f in export(tmp.path()).unwrap() {
            assert!(
                tmp.path().join(&f).is_file(),
                "{f} is named but not written"
            );
        }
        assert_eq!(
            read_all(&committed),
            read_all(tmp.path()),
            "ui/src/api/generated/gatekeeper is out of date: regenerate it (see bindings.rs)"
        );
        for (name, text) in read_all(tmp.path()) {
            assert!(!text.contains("bigint"), "{name} uses bigint");
        }
    }
}
