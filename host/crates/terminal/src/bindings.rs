//! Generated TypeScript bindings for this crate, in `ui/src/api/generated/terminal/`.
//!
//! ```text
//! HELM_UPDATE_BINDINGS=1 cargo test -p helm-terminal bindings_are_current
//! ```

use crate::{TerminalAttachResult, TerminalOpenArgs, TerminalSession};
use std::path::{Path, PathBuf};
use ts_rs::TS;

pub fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../ui/src/api/generated/terminal")
}

pub fn export(dir: &Path) -> Result<(), String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    TerminalSession::export_all_to(dir).map_err(|e| e.to_string())?;
    TerminalOpenArgs::export_all_to(dir).map_err(|e| e.to_string())?;
    TerminalAttachResult::export_all_to(dir).map_err(|e| e.to_string())?;
    let mut files: Vec<String> = std::fs::read_dir(dir)
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".ts") && n != "index.ts")
        .collect();
    files.sort();
    let mut index = String::from(
        "// Generated by host/crates/terminal (bindings.rs). Do not edit: change the Rust types and\n\
         // regenerate with `HELM_UPDATE_BINDINGS=1 cargo test -p helm-terminal bindings_are_current`.\n",
    );
    for f in &files {
        let stem = f.trim_end_matches(".ts");
        index.push_str(&format!("export type {{ {stem} }} from './{stem}.ts';\n"));
    }
    std::fs::write(dir.join("index.ts"), index).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn read_all(dir: &Path) -> Vec<(String, String)> {
        let mut out: Vec<(String, String)> = std::fs::read_dir(dir)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .map(|e| {
                        (
                            e.file_name().to_string_lossy().into_owned(),
                            std::fs::read_to_string(e.path())
                                .unwrap_or_default()
                                .replace("\r\n", "\n"),
                        )
                    })
                    .collect()
            })
            .unwrap_or_default();
        out.sort();
        out
    }

    #[test]
    fn bindings_are_current() {
        let committed = committed_dir();
        if std::env::var_os("HELM_UPDATE_BINDINGS").is_some() {
            let _ = std::fs::remove_dir_all(&committed);
            export(&committed).unwrap();
        }
        let tmp = tempfile::tempdir().unwrap();
        export(tmp.path()).unwrap();
        assert_eq!(
            read_all(&committed),
            read_all(tmp.path()),
            "ui/src/api/generated/terminal is out of date (see bindings.rs)"
        );
    }
}
